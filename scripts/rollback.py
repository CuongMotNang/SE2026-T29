"""Rollback orchestration script to safely restore a previous verified release.

Implements TASK-005 requirements:
- "Viết deploy và rollback scripts có khóa chống chạy đồng thời."
- "Deploy lỗi tự khôi phục manifest trước đó và giữ nguyên booking cũ."
- Restores image refs and config by digest without dropping database volumes (E12).
- Verifies post-rollback health and business functionality in <= 5 minutes.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

from scripts.deploy_lock import DeploymentLock, DeploymentLockError
from scripts.release_manifest import ReleaseManifest
from scripts.smoke_test import SmokeTestRunner


class Rollbacker:
    def __init__(
        self,
        target_manifest: Path | str = "deploy/previous-manifest.json",
        compose_file: Path | str = "deploy/compose.production.yaml",
        state_dir: Path | str = "deploy",
        base_url: str = "http://localhost:8000",
        readiness_timeout_seconds: float = 30.0,
        skip_container_ops: bool = False,
        dry_run: bool = False,
        acquire_lock: bool = True,
    ) -> None:
        self.target_manifest_path = Path(target_manifest).resolve()
        self.compose_file = Path(compose_file).resolve()
        self.state_dir = Path(state_dir).resolve()
        self.base_url = base_url
        self.readiness_timeout_seconds = readiness_timeout_seconds
        self.skip_container_ops = skip_container_ops
        self.dry_run = dry_run
        self.acquire_lock = acquire_lock

        self.current_manifest_file = self.state_dir / "current-manifest.json"
        self.env_file = self.state_dir / ".env.production"
        self.lock_dir = self.state_dir / ".deploy.lock"

    def execute_command(self, cmd: list[str]) -> None:
        cmd_str = " ".join(cmd)
        if self.dry_run:
            print(f"[DRY-RUN] Would execute: {cmd_str}")
            return
        print(f"[EXEC] {cmd_str}")
        result = subprocess.run(cmd, check=False, text=True, capture_output=True)
        if result.returncode != 0:
            print(
                f"[ERROR] Command failed with code {result.returncode}: {cmd_str}",
                file=sys.stderr,
            )
            if result.stdout:
                print(f"Stdout:\n{result.stdout}", file=sys.stderr)
            if result.stderr:
                print(f"Stderr:\n{result.stderr}", file=sys.stderr)
            raise RuntimeError(f"Rollback command failed: {cmd_str}")

    def prepare_environment_file(self, manifest: ReleaseManifest) -> None:
        backend_spec = manifest.images.get("backend")
        if not backend_spec:
            raise ValueError("Rollback manifest does not contain 'backend' image spec.")

        pinned_backend = backend_spec.pinned_reference
        env_content = (
            f"# Generated by rollback.py at {datetime.now(UTC).isoformat()}\n"
            f"BACKEND_IMAGE_REF={pinned_backend}\n"
            f"BOOKING_RELEASE={manifest.release}\n"
            f"BOOKING_COMMIT_SHA={manifest.commit_sha}\n"
        )
        if self.dry_run:
            print(f"[DRY-RUN] Would write .env.production:\n{env_content}")
            return

        self.state_dir.mkdir(parents=True, exist_ok=True)
        self.env_file.write_text(env_content, encoding="utf-8")
        print(f"[INFO] Restored environment configuration: {pinned_backend}")

    def recreate_containers(self, manifest: ReleaseManifest) -> None:
        backend_spec = manifest.images["backend"]
        print(f"[INFO] Restoring previous container using digest: {backend_spec.pinned_reference}")
        if not self.skip_container_ops:
            # Recreate containers without touching database volume
            compose_cmd = [
                "docker",
                "compose",
                "--env-file",
                str(self.env_file),
                "-f",
                str(self.compose_file),
                "up",
                "-d",
                "--remove-orphans",
            ]
            self.execute_command(compose_cmd)

    def run_smoke_tests(self, manifest: ReleaseManifest) -> bool:
        if self.dry_run:
            print("[DRY-RUN] Would run readiness probe and business smoke tests")
            return True
        if self.skip_container_ops:
            print("[INFO] Skipping HTTP smoke test (skip_container_ops enabled)")
            return True

        runner = SmokeTestRunner(
            base_url=self.base_url,
            readiness_timeout_seconds=self.readiness_timeout_seconds,
            expected_release=manifest.release,
            expected_commit_sha=manifest.commit_sha,
        )
        results = runner.run_all()
        for res in results:
            status = "PASS" if res.success else "FAIL"
            print(f"[{status}] ({res.duration_seconds:.2f}s) {res.step}: {res.message}")
            if not res.success:
                return False
        return True

    def _execute_rollback(self, manifest: ReleaseManifest, start_time: float) -> None:
        # 1. Restore environment config
        self.prepare_environment_file(manifest)

        # 2. Recreate containers
        self.recreate_containers(manifest)

        # 3. Verify health and business smoke test
        smoke_ok = self.run_smoke_tests(manifest)
        if not smoke_ok:
            raise RuntimeError(f"Rollback verification failed for release {manifest.release}")

        # 4. Update current manifest to the restored version
        if not self.dry_run:
            self.current_manifest_file.write_text(manifest.to_json() + "\n", encoding="utf-8")

        elapsed = time.monotonic() - start_time
        print("=" * 60)
        print(f"Rollback SUCCESSFUL for {manifest.release} in {elapsed:.2f}s!")
        print(f"Active manifest restored at: {self.current_manifest_file}")
        if elapsed <= 300.0:
            print(f"[SLO MET] Rollback completed in {elapsed:.2f}s (target <= 300s).")
        else:
            print(f"[SLO WARNING] Rollback took {elapsed:.2f}s, exceeding 300s target.")
        print("=" * 60)

    def run(self) -> None:
        start_time = time.monotonic()
        if not self.target_manifest_path.exists():
            raise FileNotFoundError(
                f"Cannot perform rollback: target manifest not found at {self.target_manifest_path}"
            )

        manifest = ReleaseManifest.load(self.target_manifest_path)
        errors = manifest.validate()
        if errors:
            raise ValueError(f"Invalid rollback manifest: {'; '.join(errors)}")

        print("=" * 60)
        print(f"Initiating ROLLBACK to release: {manifest.release}")
        print(f"Target commit SHA: {manifest.commit_sha}")
        print("Note: PostgreSQL volume is preserved; bookings will remain intact.")
        print("=" * 60)

        if self.acquire_lock:
            with DeploymentLock(
                lock_dir=self.lock_dir,
                operation="rollback",
                target_release=manifest.release,
                timeout_seconds=5.0,
            ):
                self._execute_rollback(manifest, start_time)
        else:
            self._execute_rollback(manifest, start_time)


def main() -> None:
    parser = argparse.ArgumentParser(description="Deterministic Booking API rollback tool")
    parser.add_argument(
        "--target-manifest",
        default="deploy/previous-manifest.json",
        help="Path to manifest to restore (defaults to deploy/previous-manifest.json)",
    )
    parser.add_argument("--compose-file", default="deploy/compose.production.yaml")
    parser.add_argument("--state-dir", default="deploy")
    parser.add_argument("--base-url", default="http://localhost:8000")
    parser.add_argument("--timeout", type=float, default=30.0)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--skip-container-ops", action="store_true")
    args = parser.parse_args()

    try:
        rollbacker = Rollbacker(
            target_manifest=args.target_manifest,
            compose_file=args.compose_file,
            state_dir=args.state_dir,
            base_url=args.base_url,
            readiness_timeout_seconds=args.timeout,
            skip_container_ops=args.skip_container_ops,
            dry_run=args.dry_run,
            acquire_lock=True,
        )
        rollbacker.run()
    except DeploymentLockError as exc:
        print(f"[FATAL] Lock error: {exc}", file=sys.stderr)
        sys.exit(2)
    except Exception as exc:
        print(f"[FATAL] Rollback failed: {exc}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
