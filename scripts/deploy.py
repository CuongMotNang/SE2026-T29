"""Deploy orchestration script with concurrency locking, digest verification, and auto-rollback.

Implements TASK-005 requirements:
- "Viết deploy và rollback scripts có khóa chống chạy đồng thời."
- "Deploy dùng image digest, không build lại trên VM và không dùng latest."
- "Thêm readiness timeout và smoke test nghiệp vụ sau deploy."
- "Deploy lỗi tự khôi phục manifest trước đó và giữ nguyên booking cũ."
"""

from __future__ import annotations

import argparse
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

from scripts.deploy_lock import DeploymentLock, DeploymentLockError
from scripts.release_manifest import ReleaseManifest
from scripts.smoke_test import SmokeTestRunner


def build_compose_up_command(
    env_file: Path | str,
    compose_file: Path | str,
    detach: bool = True,
    remove_orphans: bool = True,
) -> list[str]:
    """Build a deterministic docker compose up command list.

    Shared between deploy and rollback orchestration to guarantee consistent
    flag ordering (--env-file, -f, up, -d, --remove-orphans).
    """
    cmd = [
        "docker",
        "compose",
        "--env-file",
        str(env_file),
        "-f",
        str(compose_file),
        "up",
    ]
    if detach:
        cmd.append("-d")
    if remove_orphans:
        cmd.append("--remove-orphans")
    return cmd


class Deployer:
    def __init__(
        self,
        manifest_path: Path | str,
        compose_file: Path | str = "deploy/compose.production.yaml",
        state_dir: Path | str = "deploy",
        base_url: str = "http://localhost:8000",
        readiness_timeout_seconds: float = 30.0,
        dry_run: bool = False,
        skip_container_ops: bool = False,
    ) -> None:
        self.manifest_path = Path(manifest_path).resolve()
        self.compose_file = Path(compose_file).resolve()
        self.state_dir = Path(state_dir).resolve()
        self.base_url = base_url
        self.readiness_timeout_seconds = readiness_timeout_seconds
        self.dry_run = dry_run
        self.skip_container_ops = skip_container_ops

        self.current_manifest_file = self.state_dir / "current-manifest.json"
        self.previous_manifest_file = self.state_dir / "previous-manifest.json"
        self.env_file = self.state_dir / ".env.production"
        self.lock_dir = self.state_dir / ".deploy.lock"

    def execute_command(self, cmd: list[str], cwd: Path | None = None) -> None:
        cmd_str = " ".join(cmd)
        if self.dry_run:
            print(f"[DRY-RUN] Would execute: {cmd_str}")
            return
        print(f"[EXEC] {cmd_str}")
        result = subprocess.run(cmd, cwd=cwd, check=False, text=True, capture_output=True)
        if result.returncode != 0:
            print(
                f"[ERROR] Command failed with code {result.returncode}: {cmd_str}",
                file=sys.stderr,
            )
            if result.stdout:
                print(f"Stdout:\n{result.stdout}", file=sys.stderr)
            if result.stderr:
                print(f"Stderr:\n{result.stderr}", file=sys.stderr)
            raise RuntimeError(f"Command execution failed: {cmd_str}")

    def prepare_environment_file(self, manifest: ReleaseManifest) -> None:
        backend_spec = manifest.images.get("backend")
        if not backend_spec:
            raise ValueError("Manifest does not contain 'backend' image spec.")

        # Pinned reference uses exact digest (never :latest)
        pinned_backend = backend_spec.pinned_reference

        env_content = (
            f"# Generated by deploy.py at {datetime.now(UTC).isoformat()}\n"
            f"BACKEND_IMAGE_REF={pinned_backend}\n"
            f"BOOKING_RELEASE={manifest.release}\n"
            f"BOOKING_COMMIT_SHA={manifest.commit_sha}\n"
        )
        if self.dry_run:
            print(f"[DRY-RUN] Would write .env.production:\n{env_content}")
            return

        self.state_dir.mkdir(parents=True, exist_ok=True)
        self.env_file.write_text(env_content, encoding="utf-8")
        print(f"[INFO] Prepared environment config: {pinned_backend}")

    def apply_migrations(self, manifest: ReleaseManifest) -> None:
        print(f"[INFO] Checking database migration for revision: {manifest.migration_revision}")
        if self.dry_run or self.skip_container_ops:
            return
        cmd = [sys.executable, "-m", "alembic", "upgrade", "head"]
        self.execute_command(cmd, cwd=Path("backend"))

    def deploy_containers(self, manifest: ReleaseManifest) -> None:
        backend_spec = manifest.images["backend"]
        print(f"[INFO] Pulling immutable image by digest: {backend_spec.pinned_reference}")
        if not self.skip_container_ops:
            # 1. Pull pinned digest
            self.execute_command(["docker", "pull", backend_spec.pinned_reference])

            # 2. Recreate containers using docker compose builder
            compose_cmd = build_compose_up_command(self.env_file, self.compose_file)
            self.execute_command(compose_cmd)

    def run_smoke_tests(self, manifest: ReleaseManifest) -> bool:
        if self.dry_run:
            print("[DRY-RUN] Would run readiness probe and business smoke tests")
            return True
        if self.skip_container_ops:
            print("[INFO] Skipping HTTP smoke test (skip_container_ops enabled)")
            return True

        runner = SmokeTestRunner(
            base_url=self.base_url,
            readiness_timeout_seconds=self.readiness_timeout_seconds,
            expected_release=manifest.release,
            expected_commit_sha=manifest.commit_sha,
        )
        results = runner.run_all()
        for res in results:
            status = "PASS" if res.success else "FAIL"
            print(f"[{status}] ({res.duration_seconds:.2f}s) {res.step}: {res.message}")
            if not res.success:
                return False
        return True

    def trigger_auto_rollback(self) -> None:
        print(
            "[ALERT] Deployment health or smoke test failed! Triggering automatic rollback...",
            file=sys.stderr,
        )
        if not self.previous_manifest_file.exists():
            print(
                "[CRITICAL] Cannot rollback: no previous manifest recorded!",
                file=sys.stderr,
            )
            return

        from scripts.rollback import Rollbacker

        rollbacker = Rollbacker(
            target_manifest=self.previous_manifest_file,
            compose_file=self.compose_file,
            state_dir=self.state_dir,
            base_url=self.base_url,
            readiness_timeout_seconds=self.readiness_timeout_seconds,
            skip_container_ops=self.skip_container_ops,
            dry_run=self.dry_run,
            acquire_lock=False,  # Deployer process already holds deployment lock
        )
        rollbacker.run()

    def run(self) -> None:
        start_time = time.monotonic()
        manifest = ReleaseManifest.load(self.manifest_path)
        errors = manifest.validate()
        if errors:
            raise ValueError(f"Invalid target manifest: {'; '.join(errors)}")

        print("=" * 60)
        print(f"Starting deployment for release: {manifest.release}")
        print(f"Commit SHA: {manifest.commit_sha}")
        print(f"Target migration: {manifest.migration_revision}")
        print("=" * 60)

        with DeploymentLock(
            lock_dir=self.lock_dir,
            operation="deploy",
            target_release=manifest.release,
            timeout_seconds=5.0,
        ):
            # 1. Backup current manifest to previous before updating
            if self.current_manifest_file.exists():
                curr_content = self.current_manifest_file.read_text(encoding="utf-8")
                self.previous_manifest_file.write_text(curr_content, encoding="utf-8")
                print(f"[INFO] Backed up current manifest to {self.previous_manifest_file}")

            # 2. Write environment variables for compose
            self.prepare_environment_file(manifest)

            # 3. Apply database migrations
            self.apply_migrations(manifest)

            # 4. Deploy containers via compose
            try:
                self.deploy_containers(manifest)
            except Exception as exc:
                print(f"[ERROR] Container recreation failed: {exc}", file=sys.stderr)
                self.trigger_auto_rollback()
                raise

            # 5. Run readiness and smoke test
            smoke_ok = self.run_smoke_tests(manifest)
            if not smoke_ok:
                self.trigger_auto_rollback()
                raise RuntimeError(
                    f"Deployment failed post-deploy smoke tests for {manifest.release}. "
                    "Automatic rollback executed."
                )

            # 6. Save current active manifest
            if not self.dry_run:
                self.current_manifest_file.write_text(manifest.to_json() + "\n", encoding="utf-8")

            elapsed = time.monotonic() - start_time
            print("=" * 60)
            print(f"Deployment SUCCESSFUL for {manifest.release} in {elapsed:.2f}s!")
            print(f"Active manifest recorded at: {self.current_manifest_file}")
            print("=" * 60)


def main() -> None:
    parser = argparse.ArgumentParser(description="Deterministic Booking API deploy tool")
    parser.add_argument("--manifest", required=True, help="Path to release manifest JSON")
    parser.add_argument("--compose-file", default="deploy/compose.production.yaml")
    parser.add_argument("--state-dir", default="deploy")
    parser.add_argument("--base-url", default="http://localhost:8000")
    parser.add_argument("--timeout", type=float, default=30.0)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--skip-container-ops", action="store_true")
    args = parser.parse_args()

    try:
        deployer = Deployer(
            manifest_path=args.manifest,
            compose_file=args.compose_file,
            state_dir=args.state_dir,
            base_url=args.base_url,
            readiness_timeout_seconds=args.timeout,
            dry_run=args.dry_run,
            skip_container_ops=args.skip_container_ops,
        )
        deployer.run()
    except DeploymentLockError as exc:
        print(f"[FATAL] Lock error: {exc}", file=sys.stderr)
        sys.exit(2)
    except Exception as exc:  # noqa: BLE001
        print(f"[FATAL] Deployment failed: {exc}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
